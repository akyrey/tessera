-- M2: cards, per-user preferences and card photos.
-- `change_seq` comes from the single-row `change_counter` and is bumped on every
-- write, so offline clients (M3) can pull everything after their last cursor.

CREATE TABLE change_counter (
    id    INTEGER PRIMARY KEY CHECK (id = 1),
    value INTEGER NOT NULL
) STRICT;
INSERT INTO change_counter (id, value) VALUES (1, 0);

CREATE TABLE cards (
    id             BLOB PRIMARY KEY NOT NULL,  -- UUIDv7, generated by the client
    owner_id       BLOB NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    household_id   BLOB REFERENCES households (id) ON DELETE SET NULL,  -- set = shared (M4)
    store_name     TEXT NOT NULL CHECK (length(store_name) BETWEEN 1 AND 64),
    card_number    TEXT NOT NULL CHECK (length(card_number) BETWEEN 1 AND 512),
    barcode_format TEXT NOT NULL CHECK (barcode_format IN (
        'ean13', 'ean8', 'upca', 'code128', 'code39', 'itf', 'codabar',
        'qr', 'pdf417', 'aztec', 'datamatrix', 'none')),
    member_name    TEXT CHECK (length(member_name) BETWEEN 1 AND 64),
    color          TEXT CHECK (color GLOB '#[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]'),
    notes          TEXT CHECK (length(notes) BETWEEN 1 AND 1000),
    created_at     INTEGER NOT NULL,
    updated_at     INTEGER NOT NULL,
    deleted_at     INTEGER,
    change_seq     INTEGER NOT NULL
) STRICT;
CREATE INDEX cards_owner_id ON cards (owner_id);
CREATE INDEX cards_household_id ON cards (household_id) WHERE household_id IS NOT NULL;
CREATE INDEX cards_change_seq ON cards (change_seq);

CREATE TABLE card_user_prefs (
    card_id      BLOB NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    user_id      BLOB NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    is_favorite  INTEGER NOT NULL DEFAULT 0 CHECK (is_favorite IN (0, 1)),
    use_count    INTEGER NOT NULL DEFAULT 0 CHECK (use_count >= 0),
    last_used_at INTEGER,
    change_seq   INTEGER NOT NULL,
    PRIMARY KEY (card_id, user_id)
) STRICT;

-- At most one photo per side; replacing a photo gives it a new id, so the
-- image URL can be cached forever.
CREATE TABLE card_images (
    id         BLOB PRIMARY KEY NOT NULL,
    card_id    BLOB NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    kind       TEXT NOT NULL CHECK (kind IN ('front', 'back')),
    mime       TEXT NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp')),
    data       BLOB NOT NULL,
    created_at INTEGER NOT NULL,
    UNIQUE (card_id, kind)
) STRICT;
